namespace Symfony\Bridge\TuiHtml\Tests\Compatibility;

use PHPUnit\Framework\TestCase;
use Symfony\Bridge\TuiHtml\Compatibility\CompatibilityReport;
use Symfony\Bridge\TuiHtml\Compatibility\Support;
use Symfony\Bridge\TuiHtml\Compatibility\SupportLevel;
use Symfony\Bridge\TuiHtml\Compatibility\SupportProviderInterface;
use Symfony\Bridge\TuiHtml\Html\ElementRegistry;
use Symfony\Bridge\TuiHtml\Widget\TextWidget;

final class CompatibilityReportTest extends TestCase
{
    private const MATRIX = __DIR__.'/../../Resources/compatibility.json';

    public function testTheCheckedInMatrixIsUpToDate()
    {
        $json = CompatibilityReport::createDefault()->toJson();
        if (getenv('TUI_UPDATE_COMPAT')) {
            file_put_contents(self::MATRIX, $json);
        }
        $this->assertFileExists(self::MATRIX);
        $this->assertSame(file_get_contents(self::MATRIX), $json, 'Run the tests with TUI_UPDATE_COMPAT=1 to update Resources/compatibility.json.');
    }

    public function testTheCompatibilitySummaryIsUpToDate()
    {
        $file = __DIR__.'/../../COMPATIBILITY.md';
        $marker = "<!-- Generated by the tests with TUI_UPDATE_COMPAT=1 from here -->\n";
        $contents = (string) file_get_contents($file);
        $this->assertStringContainsString($marker, $contents);
        $expected = substr($contents, 0, strpos($contents, $marker) + \strlen($marker))."\n".self::summary(CompatibilityReport::createDefault());
        if (getenv('TUI_UPDATE_COMPAT')) {
            file_put_contents($file, $expected);
        }
        $this->assertSame($expected, file_get_contents($file), 'Run the tests with TUI_UPDATE_COMPAT=1 to update COMPATIBILITY.md.');
    }

    public function testEachFeatureHasOneOfFourLevels()
    {
        $report = CompatibilityReport::createDefault();
        $this->assertSame(SupportLevel::Supported, $report->getSupport('css.properties.color')->level);
        $this->assertSame(SupportLevel::Partial, $report->getSupport('css.properties.will-change')->level, 'Ignored but for the containing block it makes.');
        $this->assertSame(SupportLevel::Ignored, $report->getSupport('css.properties.user-select')->level);
        $this->assertSame(SupportLevel::Unsupported, $report->getSupport('css.properties.not-a-property')->level, 'What is not listed.');
        $this->assertSame(SupportLevel::Unsupported, $report->getSupport('html.elements.not-an-element')->level);
        $this->assertSame(['supported', 'partial', 'ignored', 'unsupported'], array_map(static fn (SupportLevel $level) => $level->value, SupportLevel::cases()));
    }

    public function testApplicationRegistrationsAreReported()
    {
        $registry = (new ElementRegistry(false))->register('app-tree', static fn () => new TextWidget(), Support::partial('No drag and drop.'));
        $features = (new CompatibilityReport([$registry]))->getFeatures();
        $this->assertSame('partial', $features['html.elements.app-tree']->level->value);
        $this->assertSame('No drag and drop.', $features['html.elements.app-tree']->note);
    }

    public function testLaterProvidersWin()
    {
        $first = new class implements SupportProviderInterface {
            public function getSupport(): array
            {
                return ['css.properties.color' => Support::supported()];
            }
        };
        $second = new class implements SupportProviderInterface {
            public function getSupport(): array
            {
                return ['css.properties.color' => Support::partial('Override.')];
            }
        };
        $this->assertSame('Override.', (new CompatibilityReport([$first, $second]))->getFeatures()['css.properties.color']->note);
    }

    public function testMarkdown()
    {
        $markdown = (new CompatibilityReport([(new ElementRegistry(false))->register('x-a', static fn () => new TextWidget(), Support::partial('a | b'))]))->toMarkdown();
        $this->assertStringContainsString('| `html.elements.x-a` | partial | a \| b |', $markdown);
    }

    private static function summary(CompatibilityReport $report): string
    {
        $kinds = [
            'html.elements' => 'HTML elements',
            'html.global_attributes' => 'HTML global attributes',
            'css.properties' => 'CSS properties',
            'css.types' => 'CSS values and functions',
            'css.selectors' => 'CSS selectors',
            'css.at-rules' => 'CSS at-rules',
            'mathml.elements' => 'MathML elements',
        ];
        $counts = [];
        foreach ($report->getFeatures() as $key => $support) {
            $kind = implode('.', \array_slice(explode('.', $key), 0, 2));
            $counts[$kinds[$kind] ?? 'Other'][$support->level->value] = ($counts[$kinds[$kind] ?? 'Other'][$support->level->value] ?? 0) + 1;
        }
        $markdown = "| | supported | partial | ignored |\n|---|---|---|---|\n";
        foreach ([...array_values($kinds), 'Other'] as $kind) {
            if (isset($counts[$kind])) {
                $markdown .= \sprintf("| %s | %d | %d | %d |\n", $kind, $counts[$kind]['supported'] ?? 0, $counts[$kind]['partial'] ?? 0, $counts[$kind]['ignored'] ?? 0);
            }
        }

        return $markdown;
    }
}
