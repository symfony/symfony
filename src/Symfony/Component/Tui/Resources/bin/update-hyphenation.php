/*
 * Writes the bundled hyphenation patterns (Widget/Text/hyphenation/*.php) from the files of hyph-utf8, in
 * https://github.com/hyphenation/tex-hyphen/tree/master/hyph-utf8/tex/generic/hyph-utf8/patterns:
 *
 *     php update-hyphenation.php path/to/patterns
 *
 * Each language is read from tex/hyph-<tag>.tex (its notice, licence and hyphenmins), txt/hyph-<tag>.pat.txt and
 * txt/hyph-<tag>.hyp.txt, if any.
 */

require_once dirname(__DIR__, 2).'/Widget/Text/Hyphenator.php';

use Symfony\Component\Tui\Widget\Text\Hyphenator;

$arguments = $_SERVER['argv'] ?? [];
if (2 !== count($arguments) || !is_dir($arguments[1])) {
    fwrite(\STDERR, "Usage: php update-hyphenation.php path/to/hyph-utf8/patterns\n");
    exit(1);
}

// The caller selects the local source directory of this maintenance command.
/**
 * @psalm-taint-escape file
 * @psalm-taint-escape ssrf
 * @psalm-taint-escape url_component
 * @psalm-taint-escape url_path
 */
$source = realpath($arguments[1]);
if (false === $source) {
    exit(1);
}

$target = dirname(__DIR__, 2).'/Widget/Text/hyphenation';
foreach (['en-us', 'fr', 'de-1996', 'es'] as $tag) {
    $tex = file_get_contents($source."/tex/hyph-$tag.tex");
    $patterns = file_get_contents($source."/txt/hyph-$tag.pat.txt");
    if (false === $tex || false === $patterns) {
        fwrite(\STDERR, "The patterns of $tag cannot be read.\n");
        exit(1);
    }
    $exceptions = is_file($source."/txt/hyph-$tag.hyp.txt") ? (string) file_get_contents($source."/txt/hyph-$tag.hyp.txt") : '';

    // The comments that start the file: its title, copyright, notice and licence
    preg_match('/\A(?:%[^\n]*\n)+/', $tex, $header);
    $notice = rtrim(preg_replace(['/^% ?/m', '/ +$/m'], [' * ', ''], rtrim($header[0] ?? '')));
    if (str_contains($notice, '*/')) {
        fwrite(\STDERR, "The notice of $tag cannot be put in a comment.\n");
        exit(1);
    }
    preg_match('/^% hyphenmins:\n(?:%[^\n]*\n)*?%\s+typesetting:\n%\s+left:\s*(\d+)\n%\s+right:\s*(\d+)/m', $tex, $mins);

    $words = static fn (string $text) => implode("\n", preg_split('/\s+/u', trim(preg_replace('/%[^\n]*/', '', $text))) ?: []);
    // Compiled once here, the letters of each pattern and its digits a line each: two explode() and an array_combine()
    // load them, nothing is parsed at run time
    $compiled = (new Hyphenator($words($patterns), $words($exceptions)))->compiled();
    $exceptions = [];
    foreach ($compiled['exceptions'] as $word => $breaks) {
        $exceptions[] = '        '.var_export((string) $word, true).' => ['.implode(', ', $breaks).'],';
    }
    file_put_contents("$target/$tag.php", "<?php\n\n/*\n * Generated by Resources/bin/update-hyphenation.php from hyph-utf8, do not edit.\n *\n".$notice."\n */\n\nreturn [\n    'left' => ".(int) ($mins[1] ?? 2).",\n    'right' => ".(int) ($mins[2] ?? 2).",\n    'longest' => ".$compiled['longest'].",\n    'letters' => ".var_export(implode("\n", array_map('strval', array_keys($compiled['patterns']))), true).",\n    'digits' => ".var_export(implode("\n", $compiled['patterns']), true).",\n    'exceptions' => [".([] !== $exceptions ? "\n".implode("\n", $exceptions)."\n    " : '')."],\n];\n");
    echo "$tag\n";
}
